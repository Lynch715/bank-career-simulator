/* 过渡期:支行副行长两年 */
function transitionText(S, succ){
  const sur = S.player.sur;
  const out = [];
  out.push("副行长的办公室在支行二楼。你分管个金和运营，弹子石成了你每周要去的地方之一。");
  if(succ) out.push(`弹子石交给了${succ.name}。头一个月${pr(succ)}每天给你打两个电话，第三个月变成一周一个。`);
  if(S.flags.signedHuang){
    out.push("第二年秋天，黄世海被分行纪委带走。渝顺商贸那份贷后报告上有你的签名，你被叫去谈了两次话。第二次谈完，你在停车场坐到天黑。");
  } else if(S.flags.exposedHuang){
    out.push("第二年秋天，黄世海被分行纪委带走。案卷里最早的一页，是你写着「库存与账面不符」的那份报告。");
  } else {
    out.push("第二年秋天，黄世海被带走配合调查，牵出来的是几笔说不清的过桥。");
  }
  out.push(`十一月，分行的任命下来了。南岸支行行长，${sur}${S.player.given}。`);
  return out;
}

