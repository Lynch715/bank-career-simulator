function open(lv){
  const vc=new VirtualConsole();vc.on('jsdomError',e=>{if(!/Not implemented/.test(e.message))errors.push(e.message);});
  const dom=new JSDOM(html,{runScripts:'dangerously',pretendToBeVisual:true,url:'http://localhost/',virtualConsole:vc,beforeParse(w){w.localStorage.setItem('thsz_save',JSON.stringify(legacy[lv-1]));}});
  const w=dom.window,d=w.document,G=w.THSZ;
  d.querySelector('#btnCont').click();
  const opts=()=>[...d.querySelectorAll('#modal .opt')];
  const pick=label=>{const el=opts().find(x=>x.textContent.includes(label));if(!el)throw Error('选项不存在：'+label);el.click();};
  const close=()=>{if(!d.querySelector('#modal').classList.contains('hidden'))opts().at(-1).click();};
  return {dom,w,d,G,opts,pick,close};
}
